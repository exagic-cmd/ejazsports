    $('#loginForm').on('submit', function(e) {
        e.preventDefault();
        var $form = $(this);
        var $submitBtn = $form.find('#loginBtn');
        var $authMessages = $('#authMessages');
        
        // Clear previous messages
        $authMessages.html('');
        
        // Disable button and show loading
        $submitBtn.prop('disabled', true).html('<i class="fas fa-spinner fa-spin"></i> Signing in...');
        
        $.ajax({
            url: $form.attr('action'),
            method: 'POST',
            data: $form.serialize(),
            headers: {
                'X-Requested-With': 'XMLHttpRequest'
            },
            success: function(response) {
                if (response.success) {
                    // Login successful - redirect immediately
                    // Success message will be shown on home page via session flash
                    if (response.redirect) {
                        window.location.href = response.redirect;
                    } else {
                        window.location.reload();
                    }
                } else {
                    // Show error message
                    $authMessages.html(
                        '<div class="alert alert-danger alert-dismissible fade show" role="alert">' +
                            '<i class="fas fa-exclamation-circle mr-2"></i>' + (response.message || 'Login failed. Please try again.') +
                            '<button type="button" class="close" data-dismiss="alert">&times;</button>' +
                        '</div>'
                    );
                    $submitBtn.prop('disabled', false).html('Login');
                }
            },
            error: function(xhr) {
                var errorMessage = 'Login failed. Please try again.';
                
                if (xhr.responseJSON) {
                    if (xhr.responseJSON.message) {
                        errorMessage = xhr.responseJSON.message;
                    } else if (xhr.responseJSON.errors) {
                        // Handle validation errors
                        var errors = xhr.responseJSON.errors;
                        var errorList = [];
                        for (var field in errors) {
                            if (errors.hasOwnProperty(field)) {
                                errorList.push(errors[field][0]);
                            }
                        }
                        errorMessage = errorList.join('<br>');
                    }
                }
                
                $authMessages.html(
                    '<div class="alert alert-danger alert-dismissible fade show" role="alert">' +
                        '<i class="fas fa-exclamation-circle mr-2"></i>' + errorMessage +
                        '<button type="button" class="close" data-dismiss="alert">&times;</button>' +
                    '</div>'
                );
                $submitBtn.prop('disabled', false).html('Login');
            }
        });
    });


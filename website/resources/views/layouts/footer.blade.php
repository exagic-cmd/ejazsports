    // Cart JS: Add to cart, remove, bulk update
    $(document).on('click', '.btn-add-cart', function(e) {
        e.preventDefault();
        var id = $(this).data('product-id');
        var variantId = $(this).data('variant-id') || null;
        var qty = $(this).data('quantity') || 1;
        if (!id) {
            if (typeof showToast === 'function') showToast('Product id missing', 'danger');
            return;
        }
        $.ajax({
            url: '{{ url('/cart/add') }}',
            method: 'POST',
            data: {
                product_id: id,
                variant_id: variantId,
                quantity: qty,
                _token: $('meta[name="csrf-token"]').attr('content')
            },
            success: function(res) {
                if (res.success) {
                    if (typeof showToast === 'function') showToast('Product added to cart!', 'success');
                    $('.cart-count').text(res.count || 0);
                    if (res.miniHtml) {
                        $('#mini-cart-content').html(res.miniHtml);
                    }
                } else {
                    if (typeof showToast === 'function') showToast(res.message || 'Could not add to cart', 'danger');
                }
            },
            error: function(xhr){
                var msg = 'Could not add to cart';
                try { msg = xhr.responseJSON.message || msg; } catch(e) {}
                if (typeof showToast === 'function') showToast(msg, 'danger');
            }
        });
    });

    // Remove from cart
    $(document).on('click', '.cart-remove', function(e){
        e.preventDefault();
        var id = $(this).data('product-id');
        if (!id) return;
        $.ajax({
            url: '{{ url('/cart/remove') }}',
            method: 'POST',
            data: { product_id: id, _token: $('meta[name="csrf-token"]').attr('content') },
            success: function(res){
                if (res.success) {
                    location.reload();
                }
            }
        });
